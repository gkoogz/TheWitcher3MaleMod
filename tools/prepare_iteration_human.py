"""Derive and officially compile manual play from the platform bootstrap.

The generated script is installed temporarily by the owned desktop launcher.
The sealed verification driver remains the single maintained source.
"""
import argparse
from pathlib import Path
import re
import shutil
from mod import ROOT, digest, write_json
from compile_native_scripts import compile_native


def prepare():
    source = ROOT/'probes/native/iteration_platform.ws'
    original = source.read_text(encoding='utf-8')
    checkpoint = 'maleModIterationStarted = MaleModNativeTestCheckpoint(200);'
    walk = '        MaleModIterationWalk();'
    if original.count(checkpoint) != 1 or original.count(walk) != 1:
        raise ValueError('Platform lifecycle changed; review the manual variant')
    lines = original.splitlines(keepends=True)
    derived = ''.join(line if line.lstrip().startswith('import function ')
                      else line.replace('MaleModNativeSealedSession()',
                                        'MaleModIterationManualSession()')
                      for line in lines)
    derived = derived.replace(checkpoint, 'maleModIterationStarted = true;')
    derived = derived.replace('MaleModNativeTestCheckpoint(201);',
                              '// Manual play performs no verification checkpoint.')
    derived = derived.replace(walk, '        // Movement uses the normal player controls.')
    derived = derived.replace('theGame.TakeScreenshot();',
                              'maleModIterationStarted = true;')
    derived = derived.replace("GetInGameConfigWrapper().SetVarValue('Game','DoNotPauseWhileStopped',\"true\");",
                              '// Manual play keeps the normal background pause preference.')
    derived = derived.replace('if (MaleModIterationManualSession() && IsPausedForReason("Constrained") && maleModIterationFloorReady) { Unpause("Constrained"); }',
                              '// Manual play retains native platform pause handling.')
    derived = ('// Generated by tools/prepare_iteration_human.py; edit iteration_platform.ws.\n'
               '// Temporary manual sandbox driver; launcher removes it when this game exits.\n'
               'function MaleModIterationManualSession() : bool { return true; }\n'
               + derived)
    target = ROOT/'probes/native/iteration_platform_human.ws'
    target.write_text(derived, encoding='utf-8')
    workspace = ROOT/'build/iteration-human-script/workspace'
    script = workspace/'scripts/local/malemod'/target.name
    script.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(target, script)
    imports = tuple(re.findall(r'^import function (MaleMod\w+)\(', derived, re.M))
    proof = compile_native(workspace, imports)
    proof['manualPlatformSourceSHA256'] = digest(source)
    proof['automaticWalk'] = False
    proof['automaticNativeCheckpoints'] = False
    output = ROOT/'build/iteration-human-script/compile.json'
    write_json(output, proof)
    print(output)
    return output


if __name__ == '__main__':
    argparse.ArgumentParser(description=__doc__).parse_args()
    prepare()
